def save(section, name, df, title, source, note="", floatfmt=None):
    folder = W / SECTIONS[section] / "tables"
    folder.mkdir(parents=True, exist_ok=True)
    df.to_csv(folder / f"{name}.csv", index=False)
    block = [f"## {title}", "", f"*File:* `tables/{name}.csv`  ", f"*Source:* {source}", ""]
    if note:
        block += [f"> {note}", ""]
    block += [md_table(df, floatfmt), ""]
    _written.setdefault(section, []).append("\n".join(block))


