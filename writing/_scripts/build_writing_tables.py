def build_length_relationship(per_reply):
    rows = []
    for s in SETTINGS:
        d = per_reply[per_reply.setting == s]
        rho, p = spearmanr(d["word_count"], d["wassa_empathy_0_10"])
        rows.append({"System": LABEL[s], "Mean words": round(d["word_count"].mean(), 1),
                     "Length OK (%)": round(d["length_ok"].mean() * 100, 1),
                     "WASSA mean": round(d["wassa_empathy_0_10"].mean(), 2),
                     "Spearman rho (length vs WASSA)": round(rho, 3), "p": round(p, 5)})
    corr = pd.DataFrame(rows)
    note = ("Longer replies score higher on WASSA inside most systems, so raw WASSA favours verbose systems. "
            "This is why Gemma-3-4B's higher WASSA is not evidence of better empathy - see the length-band table.")
    for sec in ("ch5_4", "ch5_3"):
        save(sec, "length_vs_wassa_correlation", corr, "Relationship between reply length and WASSA score",
             "computed from per-reply result files by this script", note)

    sub = per_reply[per_reply.setting.isin(["bakeoff_gemma", "bakeoff_phi", FINAL])].copy()
    bins = [0, 60, 80, 100, 120, 150, 10 ** 6]
    names = ["<60", "60-80", "80-100", "100-120", "120-150", "150+"]
    sub["Length band (words)"] = pd.cut(sub["word_count"], bins, labels=names)
    band = sub.pivot_table(index="Length band (words)", columns="setting", values="wassa_empathy_0_10",
                           aggfunc=["mean", "count"], observed=False)
    out = pd.DataFrame({"Length band (words)": names})
    for s, short in [("bakeoff_gemma", "Gemma"), ("bakeoff_phi", "Phi (top-1)"), (FINAL, "Final two-stage Phi")]:
        out[f"{short} WASSA"] = [round(band[("mean", s)].get(n, np.nan), 2) for n in names]
        out[f"{short} n"] = [int(band[("count", s)].get(n, 0)) for n in names]
    for sec in ("ch5_2a", "ch5_4"):
        save(sec, "gemma_length_band_analysis", out, "Why Gemma-3-4B was not selected: WASSA at matched reply length",
             "computed from per-reply result files by this script",
             "In every band where the systems overlap, Phi matches or beats Gemma; Gemma's advantage exists only "
             "above 120 words, which the length rule excludes. Cells with n < 10 are thin.")


